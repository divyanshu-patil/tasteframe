_SENSITIVE_WORDS = re.compile(
    r"\b(ethnic|ethnicity|race|racial|skin tone|disabled|disability|pregnan\w*|religio\w*|"
    r"muslim|hindu|christian|jewish|sikh|buddhist|wheelchair|elderly|old age|age \d+)\b",
    re.I,
)


def _key(t: str) -> str:
    t = t.strip().lower().replace("café", "cafe").replace("_", " ").replace("-", " ")
    return re.sub(r"\s+", " ", t)


_LOOKUP: dict[str, str] = {_key(t): t for t in VOCAB}
_NEUTRAL: dict[str, str] = {_key(k): v for k, v in NEUTRAL.items()}


def normalize_term(term: object) -> str | None:
    """Map a model-returned term to the vocabulary (neutralising sensitive words) or None."""
    if not isinstance(term, str):
        return None
    k = _key(term)
    if not k or _SENSITIVE_WORDS.search(k):
        return None
    if k in _NEUTRAL:
        return _NEUTRAL[k]
    if k in _LOOKUP:
        return _LOOKUP[k]
    if k.endswith("s") and k[:-1] in _LOOKUP:  # "dogs" → "dog", "sunsets" → "sunset"
        return _LOOKUP[k[:-1]]
    return None


def normalize_topic(topic: object) -> str | None:
    if not isinstance(topic, str):
        return None
    t = topic.strip().lower().replace(" ", "_").replace("-", "_")
    return t if t in TOPICS else None


def prompt_vocabulary() -> str:
    topics = "\n".join(f"  - {k}: {v}" for k, v in TOPICS.items())
    elements = "\n".join(f"  {k}: {', '.join(v)}" for k, v in ELEMENTS.items())
    return f"Topics:\n{topics}\nElement vocabulary:\n{elements}"
